// The Garden pages the two Causal Map assistants read, written into dist/assistants/ on every build, where the app
// (MapCat) and the MCP server fetch them from the browser and Rubicon's release copies the agent guidance:
//   mapcat-garden-index.md    every page tagged mapcat_core or mapcat_methods: title, url and what it is for (MapCat's prompt)
//   mapcat-garden-pages.json  each such page in full, which MapCat and the MCP server read on demand
//   agent-guidance.json       every page tagged agent_guidance in full, for MapCat, the MCP server and Rubicon
// Each page's text is its own, with its title as a heading and wiki links turned into links to the published Garden.
// Drafts (`!` in the filename) are left out, so an assistant never reads what the public cannot.
//
// Run by build_static_site.py (write_assistant_files), which owns which pages are published: it sends on stdin
// { content, files, siteUrl, readme, out }, `files` being the published pages relative to `content`, and this script
// reads only those. The walk below keeps the order the pages are read in, which decides between two pages a wiki
// link could mean.
import fs from 'node:fs/promises'
import path from 'node:path'

const MAPCAT_TAGS = new Set(['mapcat_core', 'mapcat_methods'])
const GUIDANCE_TAG = 'agent_guidance'
// Rubicon's release recognises its copies of the agent guidance by this note's `from the garden page "` phrase, and
// removes a copy carrying it once the page stops being tagged; keep that phrase.
const guidanceNote = (p) => `<!-- Generated by the Causal Map Garden build from the garden page "${p.stem}" (${p.url}). Edit that page; the next Garden build publishes it. -->`
const INDEX_NOTE = '<!-- Generated by the Causal Map Garden build (assistant_files.mjs). Do not edit by hand. -->'

function stripQuotes(value) {
  return String(value || '').trim().replace(/^['"]|['"]$/g, '').trim()
}

function parseYamlScalarOrList(raw) {
  const s = String(raw || '').trim()
  if (!s) return []
  if (s.startsWith('[') && s.endsWith(']')) {
    return s.slice(1, -1).split(',').map(stripQuotes).filter(Boolean)
  }
  return [stripQuotes(s)].filter(Boolean)
}

function parseFrontMatter(mdText) {
  const match = String(mdText || '').match(/^﻿?---\r?\n([\s\S]*?)\r?\n---\r?\n?/)
  if (!match) return { metadata: {}, body: mdText }

  const metadata = {}
  const lines = match[1].split(/\r?\n/)
  let activeKey = ''

  for (const line of lines) {
    const listMatch = line.match(/^\s*-\s+(.+?)\s*$/)
    if (listMatch && activeKey) {
      if (!Array.isArray(metadata[activeKey])) metadata[activeKey] = []
      metadata[activeKey].push(stripQuotes(listMatch[1]))
      continue
    }

    const kv = line.match(/^([A-Za-z0-9_-]+):\s*(.*?)\s*$/)
    if (!kv) continue
    const key = kv[1].trim()
    const value = kv[2].trim()
    activeKey = key
    metadata[key] = value ? parseYamlScalarOrList(value) : []
  }

  return { metadata, body: mdText.slice(match[0].length) }
}

function metadataList(metadata, ...keys) {
  for (const key of keys) {
    const val = metadata[key]
    if (Array.isArray(val)) return val.map(String).map(s => s.trim()).filter(Boolean)
    if (val != null) return parseYamlScalarOrList(val)
  }
  return []
}

function cleanTitleFromStem(stem) {
  const noAnchor = stem.replace(/\s*\(\([^)]+\)\)\s*$/g, '').trim()
  const noPrefix = noAnchor.replace(/^\s*\d[\d._-]*[a-zA-Z]*\s*[-_. ]?\s*/, '').trim()
  return (noPrefix || noAnchor || stem).replace(/\bqq\b/gi, '?').trim()
}

function pageSlugFromStem(stem) {
  const match = stem.match(/\(\(([^)]+)\)\)\s*$/)
  return match ? match[1].trim().toLowerCase() : ''
}

function firstParagraph(body) {
  const lines = String(body || '').split(/\r?\n/)
  const out = []
  let inFence = false
  for (const line of lines) {
    const trimmed = line.trim()
    if (trimmed.startsWith('```')) {
      inFence = !inFence
      continue
    }
    if (inFence) continue
    if (!trimmed) {
      if (out.length) break
      continue
    }
    if (trimmed.startsWith('#') || trimmed.startsWith('![') || trimmed.startsWith('|')) continue
    if (/^[-*]\s+/.test(trimmed)) continue
    out.push(trimmed
      .replace(/^>\s*/, '')
      .replace(/\[\[([^\]|]+)(?:\|([^\]]+))?\]\]/g, '$2$1')
      .replace(/[*_`]+/g, ''))
    if (out.join(' ').length > 220) break
  }
  const text = out.join(' ').replace(/\s+/g, ' ').trim()
  if (text.length <= 240) return text
  return `${text.slice(0, 237).replace(/\s+\S*$/, '')}...`
}

async function walkMarkdown(root) {
  const results = []
  async function walk(dir) {
    const entries = await fs.readdir(dir, { withFileTypes: true })
    for (const entry of entries) {
      if (entry.name.startsWith('.') || entry.name === 'node_modules') continue
      const full = path.join(dir, entry.name)
      if (entry.isDirectory()) {
        await walk(full)
      } else if (entry.isFile() && entry.name.toLowerCase().endsWith('.md')) {
        results.push(full)
      }
    }
  }
  await walk(root)
  return results
}

function pageUrl(siteUrl, slug) {
  if (!slug) return ''
  return `${siteUrl.replace(/\/+$/, '')}/${encodeURIComponent(slug)}/`
}

// One page as every assistant file sees it. Tags lose any leading # and are lower-cased; front-matter title and slug
// win over the filename's; a `!` anywhere in the filename makes it a draft.
async function readGardenPage(file, siteUrl) {
  const stem = path.basename(file, path.extname(file))
  const { metadata, body } = parseFrontMatter(await fs.readFile(file, 'utf8'))
  const tags = metadataList(metadata, 'tags', 'Tags').map(t => t.replace(/^#/, '').toLowerCase())
  const title = metadataList(metadata, 'title', 'Title')[0] || cleanTitleFromStem(stem.replace(/!/g, '').trim())
  const slug = metadataList(metadata, 'slug', 'mapcat_slug')[0] || pageSlugFromStem(stem)
  return { stem, draft: stem.includes('!'), metadata, body, tags, title, slug, url: pageUrl(siteUrl, slug) }
}

// Every name a wiki link may use for a page: its full basename, the basename without its number and ((slug)), and its
// title. Obsidian resolves by basename, and the build accepts all three.
function linkTargets(pages) {
  const byName = new Map()
  for (const p of pages) {
    const target = { title: p.title, url: p.draft ? '' : p.url }
    const bare = p.stem.replace(/\s*\(\([^)]+\)\)\s*$/, '').replace(/^\s*\d[\d._-]*[a-zA-Z]*\s*[-_. ]?\s*/, '').trim()
    for (const key of [p.stem, bare, p.title]) if (key) byName.set(key.toLowerCase(), target)
  }
  return byName
}

function rewriteWikiLinks(body, targets) {
  return body.replace(/\[\[([^\]|#]+)(#[^\]|]*)?(?:\|([^\]]+))?\]\]/g, (m, name, _heading, display) => {
    const t = targets.get(name.trim().toLowerCase())
    const text = (display || (t ? t.title : name)).trim()
    return t && t.url ? `[${text}](${t.url})` : text
  })
}

function parseReadmeGardenLinks(readmeText) {
  const links = []
  const re = /Ideas Garden:\s*\[([^\]]+)\]\((https:\/\/garden\.causalmap\.app\/[^)]+)\)/g
  let match
  while ((match = re.exec(readmeText))) {
    links.push({ title: match[1].trim(), url: match[2].trim() })
  }
  return links
}

// A page's text as MapCat reads it: images dropped (it cannot see them), an embedded page turned into a link to it,
// wiki links into links to the published Garden.
function mapcatText(page, targets) {
  const body = page.body
    .replace(/!\[\[[^\]]+\.(?:png|jpe?g|gif|svg|webp)(?:\|[^\]]*)?\]\]/gi, '')
    .replace(/!\[[^\]]*\]\([^)]*\)/g, '')
    .replace(/!\[\[([^\]]+)\]\]/g, (m, name) => `See [[${name}]].`)
  const text = rewriteWikiLinks(body, targets).replace(/\r\n/g, '\n').replace(/\n{3,}/g, '\n\n').trim()
  return `# ${page.title}\n\n${text}\n`
}

function mapcatIndex(taggedPages, readmeLinks) {
  const lines = []
  lines.push('# MapCat Garden index')
  lines.push('')
  lines.push(INDEX_NOTE)
  lines.push('')
  lines.push('Use these Garden pages when a user asks for the ideas behind an app feature, how to interpret an output, or when to choose one method over another. Give a short answer first, then include one relevant link.')
  lines.push('')
  lines.push('## Tagged Garden pages')
  lines.push('')

  for (const tag of ['mapcat_core', 'mapcat_methods']) {
    lines.push(`### ${tag}`)
    lines.push('')
    const pages = taggedPages.filter(p => p.tags.includes(tag)).sort((a, b) => a.title.localeCompare(b.title))
    if (!pages.length) {
      lines.push('- No tagged pages found.')
      lines.push('')
      continue
    }
    for (const page of pages) {
      lines.push(`- ${page.title}: ${page.url}`)
      if (page.summary) lines.push(`  - Use for: ${page.summary}`)
      lines.push(`  - Source: ${page.source}`)
    }
    lines.push('')
  }

  lines.push('## README-linked Garden pages')
  lines.push('')
  if (!readmeLinks.length) {
    lines.push('- No README Ideas Garden links found.')
  } else {
    const seen = new Set()
    for (const link of readmeLinks) {
      const key = `${link.title}|${link.url}`
      if (seen.has(key)) continue
      seen.add(key)
      lines.push(`- ${link.title}: ${link.url}`)
    }
  }
  lines.push('')

  lines.push('## Recoding quick distinction')
  lines.push('')
  lines.push('- Recode in the AI workflow writes cleaner labels back to the selected label set.')
  lines.push('- Collapse and Soft Recode Plus are filter/pipeline transformations for simplifying or harmonising labels in a view.')
  lines.push('- Magnetisation/soft recoding maps raw labels to user-provided magnetic labels when similarity is high enough; unmatched labels stay visible unless the app setting drops them.')
  lines.push('')

  return lines.join('\n').replace(/[ \t]+$/gm, '')
}

async function readStdin() {
  const chunks = []
  for await (const chunk of process.stdin) chunks.push(chunk)
  return Buffer.concat(chunks).toString('utf8')
}

async function main() {
  const { content, files, siteUrl, readme, out } = JSON.parse(await readStdin())
  const rel = (file) => path.relative(content, file).replace(/\\/g, '/')
  const published = new Set(files)
  const all = []
  for (const file of await walkMarkdown(content)) {
    if (published.has(rel(file))) all.push({ file, page: await readGardenPage(file, siteUrl) })
  }
  const targets = linkTargets(all.map(a => a.page))

  const taggedPages = []
  const mapcatPages = []
  const guidancePages = []
  for (const { file, page } of all) {
    if (page.draft) continue
    const source = rel(file)
    const mapcatTags = page.tags.filter(t => MAPCAT_TAGS.has(t))
    if (mapcatTags.length && !page.slug) console.error(`[assistants] "${source}" is tagged for MapCat but has no ((slug)), so it is left out`)
    if (mapcatTags.length && page.slug) {
      const useFor = metadataList(page.metadata, 'mapcat_use_for', 'mapcatUseFor', 'description', 'summary')
      taggedPages.push({ title: page.title, url: page.url, tags: mapcatTags, summary: useFor.join(', ') || firstParagraph(page.body), source })
      mapcatPages.push({ slug: page.slug, title: page.title, url: page.url, tags: mapcatTags, text: mapcatText(page, targets) })
    }
    if (page.tags.includes(GUIDANCE_TAG)) {
      if (!page.slug) throw new Error(`"${source}" is tagged ${GUIDANCE_TAG} but has no ((slug)) in its filename, so it has no stable name or URL`)
      const text = `# ${page.title}\n\n${rewriteWikiLinks(page.body, targets).replace(/\r\n/g, '\n').trim()}\n\n${guidanceNote(page)}\n`
      guidancePages.push({ slug: page.slug, title: page.title, url: page.url, text })
    }
  }
  mapcatPages.sort((a, b) => a.slug.localeCompare(b.slug))
  guidancePages.sort((a, b) => a.slug.localeCompare(b.slug))

  let readmeLinks = []
  if (readme) {
    try { readmeLinks = parseReadmeGardenLinks(await fs.readFile(readme, 'utf8')) } catch (_) {}
  }

  await fs.mkdir(out, { recursive: true })
  await fs.writeFile(path.join(out, 'mapcat-garden-index.md'), mapcatIndex(taggedPages, readmeLinks), 'utf8')
  await fs.writeFile(path.join(out, 'mapcat-garden-pages.json'), JSON.stringify(mapcatPages, null, 2) + '\n', 'utf8')
  await fs.writeFile(path.join(out, 'agent-guidance.json'), JSON.stringify(guidancePages, null, 2) + '\n', 'utf8')
  console.log(`[assistants] ${all.length} published page(s) read; ${mapcatPages.length} for MapCat, ${readmeLinks.length} README link(s), ${guidancePages.length} agent guidance [${guidancePages.map(p => p.slug).join(', ')}] -> ${out}`)
}

main().catch(err => {
  console.error(`[assistants] failed: ${err?.message || err}`)
  process.exit(1)
})
